/**
 * attendanceSlice.js — Redux Toolkit Attendance State
 * ======================================================
 * PE-2 Requirement 3: Redux Toolkit
 *
 * WHY Redux for attendance (not Context)?
 * → Attendance data is:
 *   1. Loaded asynchronously from the API
 *   2. Has multiple states: idle → loading → succeeded / failed
 *   3. Shared by THREE pages: Dashboard, Attendance, BunkCalculator
 *   4. Has user actions: changing the filter (all/safe/warning/danger)
 *   Redux handles all this cleanly. Context API doesn't handle
 *   async operations as elegantly.
 *
 * Viva question: "What is a slice in Redux Toolkit?"
 * → A slice is a collection of Redux reducer logic and actions
 *   for a single feature of your app. createSlice() generates
 *   action creators automatically from the reducer functions.
 *
 * Viva question: "What is createAsyncThunk?"
 * → It creates a thunk (a function that returns a function) that
 *   handles async operations. It automatically dispatches three
 *   action types: pending, fulfilled, and rejected — so you can
 *   track loading and error states without writing that boilerplate.
 */

import { createAsyncThunk, createSlice } from '@reduxjs/toolkit';
import { getAttendance } from '../../services/api';

// ── Async Thunk ────────────────────────────────────────────────────────────────
/**
 * fetchAttendance — async thunk that calls GET /api/attendance/:rollNumber
 *
 * When dispatched, Redux Toolkit automatically:
 *   - Dispatches fetchAttendance.pending   → sets status = 'loading'
 *   - Dispatches fetchAttendance.fulfilled → sets status = 'succeeded', stores data
 *   - Dispatches fetchAttendance.rejected  → sets status = 'failed', stores error
 */
export const fetchAttendance = createAsyncThunk(
  'attendance/fetch',                   // action type prefix
  async (rollNumber, { rejectWithValue }) => {
    try {
      const data = await getAttendance(rollNumber);
      return data; // becomes action.payload in fulfilled
    } catch (err) {
      return rejectWithValue(err.message); // becomes action.payload in rejected
    }
  }
);

// ── Initial State ──────────────────────────────────────────────────────────────
const initialState = {
  data: null,         // Full API response (overallPercentage, subjects[], etc.)
  status: 'idle',     // 'idle' | 'loading' | 'succeeded' | 'failed'
  error: null,        // Error message string when status === 'failed'
  filter: 'all',      // Active filter: 'all' | 'safe' | 'warning' | 'danger'
};

// ── Slice ──────────────────────────────────────────────────────────────────────
const attendanceSlice = createSlice({
  name: 'attendance',
  initialState,

  // Synchronous reducers
  reducers: {
    /**
     * setFilter — called when user clicks All / Safe / Warning / Danger buttons
     * Usage: dispatch(setFilter('safe'))
     * Viva: This is a synchronous state update — no API call needed,
     * just update the filter value and the component re-renders.
     */
    setFilter(state, action) {
      state.filter = action.payload;
    },

    /**
     * resetAttendance — called on logout so stale data is cleared
     */
    resetAttendance() {
      return initialState;
    },
  },

  // Async reducers — handle the three states of fetchAttendance
  extraReducers: (builder) => {
    builder
      .addCase(fetchAttendance.pending, (state) => {
        state.status = 'loading';
        state.error = null;
      })
      .addCase(fetchAttendance.fulfilled, (state, action) => {
        state.status = 'succeeded';
        state.data = action.payload; // Full attendance response
      })
      .addCase(fetchAttendance.rejected, (state, action) => {
        state.status = 'failed';
        state.error = action.payload || 'Failed to load attendance.';
      });
  },
});

// ── Action creators ────────────────────────────────────────────────────────────
// These are auto-generated by createSlice
export const { setFilter, resetAttendance } = attendanceSlice.actions;

// ── Selectors ─────────────────────────────────────────────────────────────────
/**
 * Selectors are functions that extract specific pieces of state.
 * Usage: const data = useSelector(selectAttendanceData);
 *
 * Viva: "Why use selectors?"
 * → Keeps component code clean. If the state shape changes,
 *   you only update the selector, not every component.
 */
export const selectAttendanceData   = (state) => state.attendance.data;
export const selectAttendanceStatus = (state) => state.attendance.status;
export const selectAttendanceError  = (state) => state.attendance.error;
export const selectAttendanceFilter = (state) => state.attendance.filter;

/**
 * Derived selector — returns subjects filtered by the current filter value.
 * This is computed from state; no extra API call needed.
 */
export const selectFilteredSubjects = (state) => {
  const data   = state.attendance.data;
  const filter = state.attendance.filter;
  if (!data) return [];
  if (filter === 'all') return data.subjects;
  return data.subjects.filter(
    (s) => s.status.toLowerCase() === filter
  );
};

export default attendanceSlice.reducer;

